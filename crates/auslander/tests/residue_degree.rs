//! Residue degree above one: where the public API reaches it, and where the
//! tau-tilting layer provably cannot.
//!
//! Residue degree above one is the case an `F_p` basis of `Hom` counts wrong.
//! The multiplicity of `N_i` in a minimal approximation is a dimension over
//! `D_i = End(N_i) / rad End(N_i)`, so with `d_i = dim_{F_p} D_i` an `F_p`
//! basis asks for `d_i` times too many copies. `approx.rs` counts over `D_i`.
//! Its own fixture at `d = 3` is the Kronecker module `(I_3, C)`, which is
//! hereditary and in-module. This binary runs the count from the public API
//! over a non-hereditary algebra at `d = 2`, and pins the reason no mutation
//! and no closed graph can reach the same case.
//!
//! # The obstruction
//!
//! Over a bound quiver algebra `A = kQ/I` with `k` a finite prime field,
//! every tau-rigid indecomposable has residue degree 1.
//!
//! Proof. Let `N` be tau-rigid indecomposable with
//! `End(N) / rad End(N) = L = F_{p^d}`, and base change along `L/k`, which is
//! Galois. `End(N_L) = End(N) tensor_k L` has semisimple quotient
//! `L tensor_k L = L^d`, so `N_L` is a sum of `d` pairwise non-isomorphic
//! indecomposables, and the Galois group permutes them transitively. Base
//! change is exact, carries `P_v` to `P_v tensor L`, and keeps a minimal
//! projective presentation minimal, so it commutes with `tau`. That makes the
//! sum tau-rigid over `A_L`. Twisting by a Galois element is an additive
//! autoequivalence of `mod A_L` that fixes every `P_v tensor L`, so all `d`
//! summands carry one g-vector. Bongartz completion (Adachi, Iyama, and
//! Reiten, Theorem 2.10, section 2, over an arbitrary field) makes the sum a
//! summand of a support tau-tilting pair, and the summands of such a pair
//! carry distinct g-vectors (Demonet, Iyama, and Jasso, arXiv:1503.00285,
//! section 6, over an arbitrary field). Two non-isomorphic summands with one
//! g-vector contradict that, so `d = 1`.
//!
//! The limit of the proof: it needs `k` perfect and `A` split basic. Both
//! hold here. `PrimeField` is a finite prime field, and every algebra this
//! crate builds is `kQ/I` with `I` admissible, so `A / rad A` is `k^n`. The
//! proof also covers the hereditary case, which the Tits form settles on its
//! own.
//!
//! Every approximation generator of the tau-tilting layer is a tau-rigid
//! indecomposable: `mutation.rs` approximates over the summands of `M` minus
//! one slot. So the field generality of the completeness certificate stands,
//! and its residue-degree half stays unexercised: over a prime field no
//! fixture can hand `left_approximation` a generator with `d > 1` from that
//! path. The two walk tests below are that statement in executable form, and
//! one of them runs over an algebra whose module category does hold a `d = 2`
//! brick.
//!
//! Tier: everything here is always-on. Measured on this branch in the dev
//! profile (`opt-level = 2`) on the development host, `--test-threads=1`:
//!
//! ```text
//! the whole binary        0.07 s to 0.11 s over three runs
//! ```
//!
//! A range, not a median, because the host runs other work. The per-test
//! breakdown that once stood here is not restated: it was measured before the
//! closure gate landed, and a stale number reads as a current one.

